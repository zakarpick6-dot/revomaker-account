/* REVOMAKER STEAM — API client */
(function () {
  'use strict';

  const RV = (window.RV = window.RV || {});

  class ApiError extends Error {
    constructor(status, message, code, field, retryAfter) {
      super(message || 'Request failed.');
      this.name = 'ApiError';
      this.status = status;
      this.code = code || 'error';
      this.field = field || null;
      this.retryAfter = retryAfter || null;
    }
  }

  let csrfToken = null;

  function setCsrf(token) {
    csrfToken = typeof token === 'string' && token ? token : null;
  }

  function clearCsrf() {
    csrfToken = null;
  }

  async function request(path, options = {}) {
    const { method = 'GET', body, headers = {}, timeout = 20000 } = options;
    const init = {
      method,
      credentials: 'same-origin',
      headers: { Accept: 'application/json', ...headers },
    };

    if (body !== undefined) {
      init.headers['Content-Type'] = 'application/json';
      init.body = JSON.stringify(body);
    }
    if (method !== 'GET' && method !== 'HEAD' && csrfToken) {
      init.headers['X-CSRF-Token'] = csrfToken;
    }

    let controller = null;
    let timer = null;
    if (typeof AbortController !== 'undefined') {
      controller = new AbortController();
      init.signal = controller.signal;
      timer = setTimeout(() => controller.abort(), timeout);
    }

    let response;
    try {
      response = await fetch(path, init);
    } catch (error) {
      const aborted = error && error.name === 'AbortError';
      throw new ApiError(
        0,
        aborted ? 'The request timed out. Check your connection and try again.' : 'Network error. Check your connection and try again.',
        aborted ? 'timeout' : 'network'
      );
    } finally {
      if (timer) clearTimeout(timer);
    }

    const text = await response.text();
    let data = null;
    if (text) {
      try {
        data = JSON.parse(text);
      } catch {
        data = null;
      }
    }

    if (!response.ok) {
      const detail = data && data.error ? data.error : {};
      throw new ApiError(
        response.status,
        detail.message || `Request failed (${response.status}).`,
        detail.code,
        detail.field,
        detail.retryAfter
      );
    }

    return data;
  }

  function query(params) {
    const search = new URLSearchParams();
    Object.entries(params || {}).forEach(([key, value]) => {
      if (value === undefined || value === null || value === '') return;
      search.set(key, String(value));
    });
    const text = search.toString();
    return text ? `?${text}` : '';
  }

  /* --------------------------- static catalogue -------------------------- */
  /*
   * Vercel serves this project as a read-only static site: there is no Node
   * server, no SQLite file and no /api/* handler. `public/data/site.json` is
   * generated by `npm run export:static` and mirrors the public API, so every
   * read below keeps working. Owner-only actions stay on the Node host.
   */

  const STATIC_SNAPSHOT = '/data/site.json';
  let probePromise = null;
  let snapshotPromise = null;
  let snapshotData = null;

  function probe() {
    if (!probePromise) {
      probePromise = (async () => {
        try {
          const response = await fetch('/api/health', {
            method: 'GET',
            credentials: 'same-origin',
            headers: { Accept: 'application/json' },
            cache: 'no-store',
          });
          const type = response.headers.get('content-type') || '';
          if (
            response.status === 404 ||
            response.status === 405 ||
            response.status === 501 ||
            !type.includes('json')
          ) {
            return { mode: 'static', data: null };
          }
          if (!response.ok) return { mode: 'live', data: null };
          const data = await response.json().catch(() => null);
          return { mode: data && data.mode === 'static' ? 'static' : 'live', data };
        } catch {
          return { mode: 'live', data: null };
        }
      })();
    }
    return probePromise;
  }

  function loadSnapshot() {
    if (!snapshotPromise) {
      snapshotPromise = fetch(STATIC_SNAPSHOT, {
        headers: { Accept: 'application/json' },
        cache: 'no-store',
      })
        .then((response) => {
          if (!response.ok) {
            throw new ApiError(503, 'The static catalogue is not available yet.', 'static_unavailable');
          }
          return response.json();
        })
        .then((data) => {
          if (!data || !Array.isArray(data.drops)) {
            throw new ApiError(503, 'The static catalogue is invalid.', 'static_unavailable');
          }
          snapshotData = data;
          return data;
        })
        .catch((error) => {
          snapshotPromise = null;
          throw error;
        });
    }
    return snapshotPromise;
  }

  async function staticCatalogue() {
    const result = await probe();
    if (result.mode !== 'static') return null;
    return loadSnapshot();
  }

  function readOnlyError() {
    return new ApiError(
      503,
      'The owner console needs the Node server deployment (Render, Railway or Fly.io). This Vercel build is a read-only catalogue.',
      'static_read_only'
    );
  }

  async function requireServer() {
    const result = await probe();
    if (result.mode === 'static') throw readOnlyError();
  }

  function timestamp(value) {
    const time = new Date(value || 0).getTime();
    return Number.isFinite(time) ? time : 0;
  }

  function hostOf(value) {
    try {
      return new URL(String(value)).hostname.replace(/^www\./, '');
    } catch {
      return null;
    }
  }

  function sortDrops(drops, sort = 'latest') {
    const rows = drops.slice();
    if (sort === 'az') {
      return rows.sort((a, b) =>
        String(a.title || '').localeCompare(String(b.title || ''), 'en', { sensitivity: 'base' })
      );
    }
    if (sort === 'popular' || sort === 'views') {
      return rows.sort(
        (a, b) =>
          (Number(b.views) || 0) - (Number(a.views) || 0) ||
          (sort === 'popular' ? (Number(b.clicks) || 0) - (Number(a.clicks) || 0) : 0) ||
          timestamp(b.publishedAt) - timestamp(a.publishedAt)
      );
    }
    if (sort === 'clicks') {
      return rows.sort(
        (a, b) =>
          (Number(b.clicks) || 0) - (Number(a.clicks) || 0) ||
          timestamp(b.publishedAt) - timestamp(a.publishedAt)
      );
    }
    return rows.sort(
      (a, b) =>
        timestamp(b.publishedAt) - timestamp(a.publishedAt) ||
        (Number(b.id) || 0) - (Number(a.id) || 0)
    );
  }

  function pickDrops(snapshot, params = {}) {
    const limit = Math.min(Math.max(Number.parseInt(params.limit ?? 9, 10) || 9, 1), 24);
    const page = Math.max(Number.parseInt(params.page ?? 1, 10) || 1, 1);
    let rows = snapshot.drops.slice();

    if (params.category) {
      const category = snapshot.categories.find((item) => item.slug === params.category);
      if (!category) throw new ApiError(404, 'Category not found.', 'category_not_found');
      rows = rows.filter((drop) => drop.category && drop.category.slug === category.slug);
    }

    if (params.q) {
      const term = String(params.q).trim().slice(0, 80).toLowerCase();
      if (term) {
        rows = rows.filter((drop) =>
          `${drop.title || ''}\n${drop.description || ''}`.toLowerCase().includes(term)
        );
      }
    }

    if (
      params.featured === '1' ||
      params.featured === 'true' ||
      params.featured === 1 ||
      params.featured === true
    ) {
      rows = rows.filter((drop) => drop.featured);
    }

    rows = sortDrops(rows, params.sort || 'latest');
    const total = rows.length;
    const offset = (page - 1) * limit;
    return {
      drops: rows.slice(offset, offset + limit),
      total,
      page,
      pages: Math.max(1, Math.ceil(total / limit)),
      hasMore: page * limit < total,
      limit,
    };
  }

  function pickDrop(snapshot, slug) {
    const drop = snapshot.drops.find((item) => item.slug === slug);
    if (!drop) throw new ApiError(404, 'Drop not found.', 'drop_not_found');
    const detail = { ...drop, externalHost: drop.externalHost || hostOf(drop.externalUrl) };
    const related = sortDrops(
      snapshot.drops.filter(
        (item) =>
          item.id !== drop.id &&
          item.category &&
          drop.category &&
          item.category.slug === drop.category.slug
      ),
      'views'
    ).slice(0, 4);
    return { drop: detail, related };
  }

  function pickPopular(snapshot, limit = 5) {
    const size = Math.min(Math.max(Number.parseInt(limit, 10) || 5, 1), 10);
    return { drops: (snapshot.popular || []).slice(0, size) };
  }

  function pickActivity(snapshot, days = 14) {
    const span = Math.min(Math.max(Number.parseInt(days, 10) || 14, 7), 30);
    const all = (snapshot.activity && snapshot.activity.series) || [];
    return { series: all.slice(Math.max(0, all.length - span)) };
  }

  function pickTrack(snapshot, type, slug) {
    if (type === 'visit') {
      const series = (snapshot.overview && snapshot.overview.series) || [];
      const today = series[series.length - 1];
      return {
        ok: true,
        visitors: (snapshot.overview && snapshot.overview.totalVisitors) || 0,
        visitsToday: today ? today.visits : 0,
      };
    }
    const drop = snapshot.drops.find((item) => item.slug === slug);
    if (!drop) throw new ApiError(404, 'Drop not found.', 'drop_not_found');
    if (type === 'view') return { ok: true, views: drop.views, counted: false };
    return {
      ok: true,
      clicks: drop.clicks,
      url: drop.externalUrl,
      title: drop.title,
      host: drop.externalHost || hostOf(drop.externalUrl),
    };
  }

  const api = {
    request,
    get: (path) => request(path),
    post: (path, body) => request(path, { method: 'POST', body }),
    patch: (path, body) => request(path, { method: 'PATCH', body }),
    delete: (path, body) => request(path, { method: 'DELETE', body }),
    setCsrf,
    clearCsrf,
    get csrf() {
      return csrfToken;
    },

    /* ---------------------------- public ---------------------------- */
    stats: async () => {
      const snapshot = await staticCatalogue();
      return snapshot ? snapshot.overview : request('/api/stats/overview');
    },
    categories: async () => {
      const snapshot = await staticCatalogue();
      return snapshot ? { categories: snapshot.categories } : request('/api/categories');
    },
    drops: async (params) => {
      const snapshot = await staticCatalogue();
      return snapshot ? pickDrops(snapshot, params) : request(`/api/drops${query(params)}`);
    },
    drop: async (slug) => {
      const snapshot = await staticCatalogue();
      return snapshot ? pickDrop(snapshot, slug) : request(`/api/drops/${encodeURIComponent(slug)}`);
    },
    popular: async (limit = 5) => {
      const snapshot = await staticCatalogue();
      return snapshot ? pickPopular(snapshot, limit) : request(`/api/popular?limit=${Number(limit) || 5}`);
    },
    activity: async (days = 14) => {
      const snapshot = await staticCatalogue();
      return snapshot ? pickActivity(snapshot, days) : request(`/api/activity?days=${Number(days) || 14}`);
    },
    health: async () => {
      const result = await probe();
      if (result.mode === 'static') {
        return result.data || { ok: true, service: 'revomaker-steam', version: '1.0.0', mode: 'static' };
      }
      return result.data || request('/api/health');
    },
    setupStatus: async () => {
      const snapshot = await staticCatalogue();
      return snapshot ? snapshot.setup : request('/api/setup-status');
    },

    track: {
      visit: async (path) => {
        const snapshot = await staticCatalogue();
        if (snapshot) return pickTrack(snapshot, 'visit');
        return request('/api/visit', { method: 'POST', body: { path: path || location.pathname } });
      },
      view: async (slug) => {
        const snapshot = await staticCatalogue();
        if (snapshot) return pickTrack(snapshot, 'view', slug);
        return request(`/api/drops/${encodeURIComponent(slug)}/view`, { method: 'POST', body: {} });
      },
      click: async (slug) => {
        const snapshot = await staticCatalogue();
        if (snapshot) return pickTrack(snapshot, 'click', slug);
        return request(`/api/drops/${encodeURIComponent(slug)}/click`, { method: 'POST', body: {} });
      },
    },

    /* ----------------------------- auth ----------------------------- */
    auth: {
      async login(email, password) {
        await requireServer();
        const data = await request('/api/auth/login', { method: 'POST', body: { email, password } });
        setCsrf(data.csrfToken);
        return data;
      },
      async me() {
        const result = await probe();
        if (result.mode === 'static') {
          throw new ApiError(401, 'Authentication required.', 'unauthenticated');
        }
        return request('/api/auth/me');
      },
      async logout() {
        await requireServer();
        return request('/api/auth/logout', { method: 'POST', body: {} });
      },
      async changePassword(currentPassword, newPassword) {
        await requireServer();
        return request('/api/auth/password', {
          method: 'POST',
          body: { currentPassword, newPassword },
        });
      },
      async sessions() {
        await requireServer();
        return request('/api/auth/sessions');
      },
      async revokeSession(id) {
        await requireServer();
        return request(`/api/auth/sessions/${Number(id)}`, { method: 'DELETE' });
      },
    },

    /* ----------------------------- admin ---------------------------- */
    admin: {
      overview: async () => {
        await requireServer();
        return request('/api/admin/overview');
      },
      analytics: async (days = 30) => {
        await requireServer();
        return request(`/api/admin/analytics?days=${Number(days) || 30}`);
      },
      drops: async (params) => {
        await requireServer();
        return request(`/api/admin/drops${query(params)}`);
      },
      drop: async (id) => {
        await requireServer();
        return request(`/api/admin/drops/${Number(id)}`);
      },
      dropStats: async (id) => {
        await requireServer();
        return request(`/api/admin/drops/${Number(id)}/stats`);
      },
      createDrop: async (payload) => {
        await requireServer();
        return request('/api/admin/drops', { method: 'POST', body: payload });
      },
      updateDrop: async (id, payload) => {
        await requireServer();
        return request(`/api/admin/drops/${Number(id)}`, { method: 'PATCH', body: payload });
      },
      deleteDrop: async (id) => {
        await requireServer();
        return request(`/api/admin/drops/${Number(id)}`, { method: 'DELETE' });
      },
      categories: async () => {
        await requireServer();
        return request('/api/admin/categories');
      },
      createCategory: async (payload) => {
        await requireServer();
        return request('/api/admin/categories', { method: 'POST', body: payload });
      },
      updateCategory: async (id, payload) => {
        await requireServer();
        return request(`/api/admin/categories/${Number(id)}`, { method: 'PATCH', body: payload });
      },
      deleteCategory: async (id) => {
        await requireServer();
        return request(`/api/admin/categories/${Number(id)}`, { method: 'DELETE' });
      },
      activity: async () => {
        await requireServer();
        return request('/api/admin/activity');
      },
      owners: async () => {
        await requireServer();
        return request('/api/admin/owners');
      },
    },

    /* ------------------------- static helpers ------------------------ */
    static: {
      ready: () => probe().then((result) => result.mode),
      isStatic: () => Boolean(snapshotData),
      goUrl: (slug) => {
        if (!snapshotData) return null;
        const drop = snapshotData.drops.find((item) => item.slug === slug);
        return drop && drop.externalUrl ? drop.externalUrl : null;
      },
      snapshot: () => snapshotData,
    },
  };

  RV.ApiError = ApiError;
  RV.api = api;
})();
